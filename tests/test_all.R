source("R/simulation.R")
near <- function(x,y,tol=1e-8)
  stopifnot(isTRUE(all.equal(unname(x),unname(y),tolerance=tol)))
expect_error <- function(expr)
  stopifnot(inherits(try(force(expr),silent=TRUE),"try-error"))

near(win_probability(2,10),0.2)
near(markov_moments(2,10)["mean_time"],16)
near(markov_moments(2,10)["win"],0.2)
baseline <- exact_summary(2,10,0.5,10)
near(baseline["end_by_horizon"],0.560546875)
near(baseline["win_by_horizon"],0.01171875)
near(win_probability(0,10),0)
near(win_probability(10,10),1)
near(win_probability(2,10,0),0)
near(win_probability(2,10,1),1)
for (p in c(0.25,0.45,0.5,0.55,0.75)) {
  near(win_probability(2,10,p),markov_moments(2,10,p)["win"])
  f <- first_passage(2,10,p,500)
  near(sum(f$win),win_probability(2,10,p),1e-7)
  stopifnot(all(f$ruin>=0),all(f$win>=0),
            sum(f$ruin+f$win)<=1+1e-10)
}
for (N in 2:15) for (s in seq_len(N-1L)) {
  near(markov_moments(s,N)["mean_time"],s*(N-s))
  near(markov_moments(s,N)["win"],s/N)
}
a <- simulate_ruin(250,seed=999)
b <- simulate_ruin(250,seed=999)
stopifnot(identical(a,b),all(a$steps%%2L==0L),
          all(a$steps>=2L),is.logical(a$won))
